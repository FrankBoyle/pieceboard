const MARKER = '<!-- Generated by Pieceboard; safe to regenerate. -->';
const LEGACY_MARKER = '<!-- Generated by UI Sheet; safe to regenerate. -->';

async function writeAtomically(file, content) {
  const temp = path.join(path.dirname(file), `.pieceboard-report-${randomUUID()}.tmp`);
  let owned = false;
  try {
    const handle = await fs.open(temp, 'wx', 0o600);
    owned = true;
    try { await handle.writeFile(content, 'utf8'); } finally { await handle.close(); }
    for (let attempt = 1; ; attempt++) {
      try { await fs.rename(temp, file); owned = false; break; }
      catch (error) {
        if (process.platform !== 'win32' || !['EPERM', 'EBUSY', 'EACCES'].includes(error.code) || attempt >= 6) throw error;
        await new Promise((resolve) => setTimeout(resolve, 25 * attempt));
      }
    }
  } finally { if (owned) await fs.rm(temp, { force: true }); }
}

async function canReplace(file, kind) {
  let contents;
  try { contents = await fs.readFile(file, 'utf8'); }
  catch (error) { if (error.code === 'ENOENT') return; throw error; }
  let generated = contents.startsWith(MARKER) || contents.startsWith(LEGACY_MARKER);
  if (kind === 'json') {
    try { generated = JSON.parse(contents).format === 'ui-sheet/v1'; } catch { generated = false; }
  }
  if (!generated) throw new Error(`Refusing to overwrite a file that was not generated by Pieceboard: ${file}`);
}

