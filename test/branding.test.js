import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { promisify } from 'node:util';
import { execFile } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { writeReport } from '../src/report.js';

const execFileAsync = promisify(execFile);
const cli = fileURLToPath(new URL('../bin/ui-sheet.js', import.meta.url));

test('generated report uses Pieceboard branding and retains legacy generated-file ownership', async (t) => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'pieceboard-brand-'));
  t.after(() => fs.rm(directory, { recursive: true, force: true }));
  const data = { format: 'ui-sheet/v1', name: 'Example', items: [], warnings: [] };
  const htmlPath = path.join(directory, 'index.html');
  const dataPath = path.join(directory, 'ui-sheet.json');

  await writeReport(data, directory);
  let html = await fs.readFile(htmlPath, 'utf8');
  assert.match(html, /Generated by Pieceboard/);
  assert.match(html, /<title>Pieceboard<\/title>/);
  assert.match(html, /pieceboard/);
  assert.match(html, /PIECEBOARD/);
  assert.match(html, /<svg class="brand-mark" aria-hidden="true"/);
  assert.match(html, /href="data:image\/png;base64,[A-Za-z0-9+/]+=*"/);
  assert.equal(JSON.parse(await fs.readFile(dataPath, 'utf8')).format, 'ui-sheet/v1');

  await fs.writeFile(htmlPath, '<!-- Generated by UI Sheet; safe to regenerate. -->\nold report');
  await writeReport(data, directory);
  html = await fs.readFile(htmlPath, 'utf8');
  assert.match(html, /Generated by Pieceboard/);
  assert.match(html, /<title>Pieceboard<\/title>/);
});

test('CLI help and human-readable errors use Pieceboard branding', async () => {
  const { stdout } = await execFileAsync(process.execPath, [cli, '--help']);
  assert.match(stdout, /^Pieceboard —/);

  await assert.rejects(execFileAsync(process.execPath, [cli, 'unknown-command']), (error) => {
    assert.match(error.stderr, /^Pieceboard: Unknown command:/);
    assert.match(error.stderr, /Pieceboard —/);
    return true;
  });
});
